// GeneratedMainDir is the directory, relative to the project root, holding the
// generated server entry point: web/server/ (one main per folder; the folder is the
// binary). It must be inside the project: outside the module tree the Go
// toolchain cannot resolve the project's own imports.
const (
	GeneratedMainDir      = "web/server"
	GeneratedMainFilename = "main.go"

	// GeneratedMigrateDir is the app's migration binary, at the project root: the same binary for webtyp dev, the
	// self-host supervisor and a Worker pre-deploy.
	GeneratedMigrateDir = "migrate"

	// ConfigDir is the folder where an app declares itself (config/app.go).
	ConfigDir = "config"
	// AppVarName is the variable an app declares in ConfigDir when it is one appkit.App.
	AppVarName = "App"

	// goModFilename is the module manifest read for the module path.
	goModFilename = "go.mod"
	// moduleDirectivePrefix is the token that opens the module line in go.mod.
	moduleDirectivePrefix = "module"
	// runServerFuncName is the function a config/ declares when the app starts its own server.
	runServerFuncName = "RunServer"
)

// MainConfig is what the generated main hardcodes.
type MainConfig struct {
	Port      string
	PublicDir string
	PlainHTTP bool
}

// HasRoutes reports whether the project declares routes and therefore needs a
// compiled server process.
func HasRoutes(rootDir string) bool {
	if HasApp(rootDir) || HasRunServer(rootDir) {
		return true
	}
	routesFile := filepath.Join(rootDir, routescan.DefaultFile)
	_, err := os.Stat(routesFile)
	return err == nil
}

// HasApp reports whether config/ declares `var App` (an appkit.App).
func HasApp(rootDir string) bool { return configDeclares(rootDir, AppVarName, false) }

// HasRunServer reports whether config/ declares `func RunServer`: the app starts its own server.
func HasRunServer(rootDir string) bool { return configDeclares(rootDir, runServerFuncName, true) }

// configDeclares reports whether a non-test file of config/ declares name as a
// func (fn) or as a package-level var (!fn).
func configDeclares(rootDir, name string, fn bool) bool {
	configDir := filepath.Join(rootDir, ConfigDir)
	entries, err := os.ReadDir(configDir)
	if err != nil {
		return false
	}
	fset := token.NewFileSet()
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		node, err := parser.ParseFile(fset, filepath.Join(configDir, entry.Name()), nil, 0)
		if err != nil {
			continue
		}
		for _, decl := range node.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if fn && d.Recv == nil && d.Name.Name == name {
					return true
				}
			case *ast.GenDecl:
				if fn || d.Tok != token.VAR {
					continue
				}
				for _, spec := range d.Specs {
					if vs, ok := spec.(*ast.ValueSpec); ok {
						for _, n := range vs.Names {
							if n.Name == name {
								return true
							}
						}
					}
				}
			}
		}
	}
	return false
}

// ReadModulePath returns the module path of the project at rootDir (the `module` line of its go.mod), or the folder name when go.mod cannot be read.
//
// Example: modulePath := server.ReadModulePath(rootDir)
func ReadModulePath(rootDir string) string {
	content, err := os.ReadFile(filepath.Join(rootDir, goModFilename))
	if err != nil {
		return filepath.Base(rootDir)
	}
	lines := strings.Split(string(content), "\n")
	for _, line := range lines {
		fields := strings.Fields(strings.TrimSpace(line))
		if len(fields) >= 2 && fields[0] == moduleDirectivePrefix {
			return fields[1]
		}
	}
	return filepath.Base(rootDir)
}

// IsGenerated reports whether a file's content was written by webtyp (its header says so), so it may be rewritten;
// a file without that header is the developer's and is never touched. The one place that knows the header.
//
// Example: if server.IsGenerated(string(content)) { … }
func IsGenerated(content string) bool {
	return strings.Contains(content, "Code generated by webtyp.com/") || strings.Contains(content, "Code generated by https://webtyp.com")
}
