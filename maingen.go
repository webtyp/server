// appVarName is the variable an app declares in config/ when it is one appkit.App.
const appVarName = "App"

// HasRoutes reports whether the project declares routes and therefore needs a
// compiled server process.
func HasRoutes(rootDir string) bool {
	if HasApp(rootDir) || hasRunServer(rootDir) {
		return true
	}
	routesFile := filepath.Join(rootDir, routescan.DefaultFile)
	_, err := os.Stat(routesFile)
	return err == nil
}

// HasApp reports whether config/ declares `var App` (an appkit.App).
func HasApp(rootDir string) bool { return configDeclares(rootDir, appVarName, false) }

func hasRunServer(rootDir string) bool { return configDeclares(rootDir, "RunServer", true) }

// configDeclares reports whether a non-test file of config/ declares name as a
// func (fn) or as a package-level var (!fn).
func configDeclares(rootDir, name string, fn bool) bool {
	configDir := filepath.Join(rootDir, "config")
	entries, err := os.ReadDir(configDir)
	if err != nil {
		return false
	}
	fset := token.NewFileSet()
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		node, err := parser.ParseFile(fset, filepath.Join(configDir, entry.Name()), nil, 0)
		if err != nil {
			continue
		}
		for _, decl := range node.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if fn && d.Recv == nil && d.Name.Name == name {
					return true
				}
			case *ast.GenDecl:
				if fn || d.Tok != token.VAR {
					continue
				}
				for _, spec := range d.Specs {
					if vs, ok := spec.(*ast.ValueSpec); ok {
						for _, n := range vs.Names {
							if n.Name == name {
								return true
							}
						}
					}
				}
			}
		}
	}
	return false
}

func readModulePath(rootDir string) string {
	content, err := os.ReadFile(filepath.Join(rootDir, goModFilename))
	if err != nil {
		return filepath.Base(rootDir)
	}
	lines := strings.Split(string(content), "\n")
	for _, line := range lines {
		fields := strings.Fields(strings.TrimSpace(line))
		if len(fields) >= 2 && fields[0] == moduleDirectivePrefix {
			return fields[1]
		}
	}
	return filepath.Base(rootDir)
}

// GenerateMain writes the server entry point for the project at rootDir and
// returns the absolute path of the written file.
//
// modulePath is the project's module path, read from go.mod.
func GenerateMain(rootDir, modulePath string, cfg MainConfig) (string, error) {
	outDir := filepath.Join(rootDir, filepath.FromSlash(GeneratedMainDir))
	if err := os.MkdirAll(outDir, dirPerm); err != nil {
		return "", fmt.Errorf("creating build directory: %w", err)
	}

	mainFile := filepath.Join(outDir, GeneratedMainFilename)
	absPath, err := filepath.Abs(mainFile)
	if err != nil {
		return "", fmt.Errorf("resolving absolute path: %w", err)
	}

	if content, readErr := os.ReadFile(absPath); readErr == nil {
		if !IsGenerated(string(content)) {
			return absPath, nil
		}
	}

	data := mainTemplateData{
		ModulePath: modulePath,
		Port:       cfg.Port,
		PublicDir:  cfg.PublicDir,
		PlainHTTP:  cfg.PlainHTTP,
	}

	tmplText := mainTemplateText
	if HasApp(rootDir) {
		tmplText = appServerTemplateText
		if err := writeGenerated(filepath.Join(rootDir, "web", "browser", GeneratedMainFilename), appBrowserTemplateText, data); err != nil {
			return "", err
		}
		if err := generateMigrationsFile(rootDir); err != nil {
			return "", err
		}
		if err := writeGenerated(filepath.Join(rootDir, GeneratedMigrateDir, GeneratedMainFilename), migrateTemplateText, data); err != nil {
			return "", err
		}
		if err := writeOnce(filepath.Join(rootDir, "config", GeneratedRemovedFile), removedTemplateText); err != nil {
			return "", err
		}
	} else if hasRunServer(rootDir) {
		tmplText = runServerTemplateText
	} else {
		routesFile := filepath.Join(rootDir, routescan.DefaultFile)
		data.RegisterArgs = detectRegisterArgs(routesFile)
	}

	tmpl, err := template.New("main").Parse(tmplText)
	if err != nil {
		return "", fmt.Errorf("parsing main template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("executing main template: %w", err)
	}

	if err := os.WriteFile(absPath, buf.Bytes(), filePerm); err != nil {
		return "", fmt.Errorf("writing generated main file: %w", err)
	}

	return absPath, nil
}

// writeGenerated renders tmplText to path unless path holds a hand-written file.
func writeGenerated(path, tmplText string, data any) error {
	if content, err := os.ReadFile(path); err == nil && !IsGenerated(string(content)) {
		return nil
	}
	tmpl, err := template.New("gen").Parse(tmplText)
	if err != nil {
		return fmt.Errorf("parsing template: %w", err)
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return fmt.Errorf("executing template: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(path), dirPerm); err != nil {
		return fmt.Errorf("creating directory: %w", err)
	}
	return os.WriteFile(path, buf.Bytes(), filePerm)
}

// writeOnce writes text to path only when no file is there: config/removed.go holds the developer's answers
// once webtyp dev writes it, and the generator must never put the empty list back.
func writeOnce(path, text string) error {
	if _, err := os.Stat(path); err == nil {
		return nil
	} else if !os.IsNotExist(err) {
		return fmt.Errorf("reading %s: %w", path, err)
	}
	if err := os.MkdirAll(filepath.Dir(path), dirPerm); err != nil {
		return fmt.Errorf("creating directory: %w", err)
	}
	return os.WriteFile(path, []byte(text), filePerm)
}

// IsGenerated reports whether a file's content was written by webtyp (its header says so), so it may be rewritten;
// a file without that header is the developer's and is never touched. The one place that knows the header.
//
// Example: if server.IsGenerated(string(content)) { … }
func IsGenerated(content string) bool {
	return strings.Contains(content, "Code generated by webtyp.com/") || strings.Contains(content, "Code generated by https://webtyp.com")
}

// detectRegisterArgs renders the argument list for the routes.Register call in
// the generated main. routescan reports the routes a project declares but not
// the signature of Register itself, so its arity is read here from the AST:
// the router is always the first argument, and every dependency parameter after
// it becomes a nil placeholder the developer fills in. Any parse failure falls
// back to the single-argument form rather than aborting generation.
func detectRegisterArgs(routesFile string) string {
	fset := token.NewFileSet()
	node, err := parser.ParseFile(fset, routesFile, nil, 0)
	if err != nil {
		return routerArgExpr
	}

	var targetFunc *ast.FuncDecl
	for _, decl := range node.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Type == nil || fn.Type.Params == nil {
			continue
		}
		if fn.Name.Name == registerFuncName {
			targetFunc = fn
			break
		}
		if targetFunc == nil && len(fn.Type.Params.List) > 0 {
			if isRouterParam(fn.Type.Params.List[0].Type) {
				targetFunc = fn
			}
		}
	}

	if targetFunc == nil {
		return routerArgExpr
	}

	paramCount := 0
	for _, field := range targetFunc.Type.Params.List {
		if len(field.Names) == 0 {
			paramCount++
		} else {
			paramCount += len(field.Names)
		}
	}

	if paramCount <= 1 {
		return routerArgExpr
	}

	args := make([]string, paramCount)
	args[0] = routerArgExpr
	for i := 1; i < paramCount; i++ {
		args[i] = dependencyArg
	}
	return strings.Join(args, ", ")
}

func isRouterParam(expr ast.Expr) bool {
	sel, ok := expr.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	ident, ok := sel.X.(*ast.Ident)
	if !ok {
		return false
	}
	return (ident.Name == "router" || ident.Name == "Router") && sel.Sel.Name == "Router"
}

type migrationStepData struct {
	Name       string
	Alias      string
	ImportPath string
}

type migrationsTemplateData struct {
	Steps []migrationStepData
}

func generateMigrationsFile(rootDir string) error {
	configDir := filepath.Join(rootDir, "config")
	entries, err := os.ReadDir(configDir)
	if err != nil {
		return err
	}

	fset := token.NewFileSet()
	var (
		moduleIdents  []string
		identToImport = make(map[string]string)
	)

	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		filePath := filepath.Join(configDir, entry.Name())
		node, err := parser.ParseFile(fset, filePath, nil, 0)
		if err != nil {
			continue
		}

		for _, imp := range node.Imports {
			impPath := strings.Trim(imp.Path.Value, `"`)
			if imp.Name != nil && imp.Name.Name != "" && imp.Name.Name != "_" && imp.Name.Name != "." {
				identToImport[imp.Name.Name] = impPath
			} else {
				base := filepath.Base(impPath)
				identToImport[base] = impPath
				if base == "module" {
					parent := filepath.Base(filepath.Dir(impPath))
					identToImport[parent] = impPath
				}
			}
		}

		for _, decl := range node.Decls {
			genDecl, ok := decl.(*ast.GenDecl)
			if !ok || genDecl.Tok != token.VAR {
				continue
			}
			for _, spec := range genDecl.Specs {
				valSpec, ok := spec.(*ast.ValueSpec)
				if !ok {
					continue
				}
				for i, name := range valSpec.Names {
					if name.Name != appVarName || i >= len(valSpec.Values) {
						continue
					}
					compLit, ok := valSpec.Values[i].(*ast.CompositeLit)
					if !ok {
						continue
					}
					for _, elt := range compLit.Elts {
						kv, ok := elt.(*ast.KeyValueExpr)
						if !ok {
							continue
						}
						keyIdent, ok := kv.Key.(*ast.Ident)
						if !ok || keyIdent.Name != "Modules" {
							continue
						}
						modsLit, ok := kv.Value.(*ast.CompositeLit)
						if !ok {
							continue
						}
						for _, modElt := range modsLit.Elts {
							if sel, ok := modElt.(*ast.SelectorExpr); ok {
								if ident, ok := sel.X.(*ast.Ident); ok {
									moduleIdents = append(moduleIdents, ident.Name)
								}
							}
						}
					}
				}
			}
		}
	}

	var steps []migrationStepData
	usedAliases := make(map[string]bool)

	for _, ident := range moduleIdents {
		impPath, ok := identToImport[ident]
		if !ok {
			continue
		}
		repoPath := impPath
		if strings.HasSuffix(impPath, "/module") {
			repoPath = strings.TrimSuffix(impPath, "/module")
		}
		migratePkgPath := repoPath + "/migrate"
		repoName := filepath.Base(repoPath)

		if !packageHasMigrate(rootDir, migratePkgPath, repoPath) {
			continue
		}

		alias := ident + "migrate"
		if usedAliases[alias] {
			alias = repoName + "migrate"
		}
		usedAliases[alias] = true

		steps = append(steps, migrationStepData{
			Name:       repoName,
			Alias:      alias,
			ImportPath: migratePkgPath,
		})
	}

	_ = os.Remove(filepath.Join(rootDir, GeneratedMigrateDir, "migrations.go"))
	_ = os.Remove(filepath.Join(rootDir, GeneratedMigrateDir, "migrations.go"))
	return writeGenerated(filepath.Join(rootDir, "config", "migrations.go"), migrationsTemplateText, migrationsTemplateData{Steps: steps})
}

func packageHasMigrate(rootDir, migratePkgPath, repoPath string) bool {
	modPath := readModulePath(rootDir)
	if modPath != "" && strings.HasPrefix(migratePkgPath, modPath+"/") {
		rel := strings.TrimPrefix(migratePkgPath, modPath+"/")
		localDir := filepath.Join(rootDir, rel)
		if dirHasMigrateFunc(localDir) {
			return true
		}
	}

	replaces := readModReplaces(rootDir)
	if repTarget, ok := replaces[repoPath]; ok {
		targetDir := repTarget
		if !filepath.IsAbs(targetDir) {
			targetDir = filepath.Join(rootDir, targetDir)
		}
		if dirHasMigrateFunc(filepath.Join(targetDir, "migrate")) {
			return true
		}
	}
	if repTarget, ok := replaces[migratePkgPath]; ok {
		targetDir := repTarget
		if !filepath.IsAbs(targetDir) {
			targetDir = filepath.Join(rootDir, targetDir)
		}
		if dirHasMigrateFunc(targetDir) {
			return true
		}
	}

	repoBase := filepath.Base(repoPath)
	candidates := []string{
		filepath.Join(rootDir, repoBase, "migrate"),
		filepath.Join(rootDir, "..", repoBase, "migrate"),
		filepath.Join(rootDir, "..", "modules", repoBase, "migrate"),
		filepath.Join(rootDir, "..", "..", "veltylabs", "modules", repoBase, "migrate"),
		filepath.Join(rootDir, "..", "..", "webtyp", repoBase, "migrate"),
	}
	for _, cand := range candidates {
		if dirHasMigrateFunc(cand) {
			return true
		}
	}

	if pkg, err := build.Default.Import(migratePkgPath, rootDir, 0); err == nil && pkg.Dir != "" {
		if dirHasMigrateFunc(pkg.Dir) {
			return true
		}
	}

	return false
}

func dirHasMigrateFunc(dir string) bool {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, nil, 0)
	if err != nil {
		return false
	}
	for _, pkg := range pkgs {
		for _, f := range pkg.Files {
			for _, decl := range f.Decls {
				fn, ok := decl.(*ast.FuncDecl)
				if ok && fn.Recv == nil && fn.Name.Name == "Migrate" {
					return true
				}
			}
		}
	}
	return false
}

func readModReplaces(rootDir string) map[string]string {
	replaces := make(map[string]string)
	data, err := os.ReadFile(filepath.Join(rootDir, "go.mod"))
	if err != nil {
		return replaces
	}
	lines := strings.Split(string(data), "\n")
	inReplaceBlock := false
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "replace (") {
			inReplaceBlock = true
			continue
		}
		if inReplaceBlock {
			if trimmed == ")" {
				inReplaceBlock = false
				continue
			}
			parseReplaceLine(trimmed, replaces)
		} else if strings.HasPrefix(trimmed, "replace ") {
			parseReplaceLine(strings.TrimPrefix(trimmed, "replace "), replaces)
		}
	}
	return replaces
}

func parseReplaceLine(line string, replaces map[string]string) {
	parts := strings.Split(line, "=>")
	if len(parts) == 2 {
		src := strings.TrimSpace(parts[0])
		dst := strings.TrimSpace(parts[1])
		srcFields := strings.Fields(src)
		if len(srcFields) > 0 {
			src = srcFields[0]
		}
		dstFields := strings.Fields(dst)
		if len(dstFields) > 0 {
			dst = dstFields[0]
		}
		replaces[src] = dst
	}
}
